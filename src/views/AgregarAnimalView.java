    private void jComboBoxAlimentacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBoxAlimentacionActionPerformed
        String seleccion = (String) jComboBoxAlimentacion.getSelectedItem();

        if (seleccion.equals("CARNIVORO")) {
            jTextFieldPorcentajeFijo.setEnabled(true);
            jTextFieldKgFijos.setEnabled(false);
            jTextFieldKgFijos.setText("");
        } else if (seleccion.equals("HERBIVORO")) {
            jTextFieldKgFijos.setEnabled(true);
            jTextFieldPorcentajeFijo.setEnabled(false);
            jTextFieldPorcentajeFijo.setText("");
        } else {
            jTextFieldKgFijos.setEnabled(false);
            jTextFieldPorcentajeFijo.setEnabled(false);
            jTextFieldKgFijos.setText("");
            jTextFieldPorcentajeFijo.setText("");
        }

        if (!seleccion.equals("Seleccione:")) {
            actualizarComboSectores(seleccion);
        }
    }//GEN-LAST:event_jComboBoxAlimentacionActionPerformed

    private void jButtonAgregarAnimalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAgregarAnimalActionPerformed
    String especieNombre = jTextFieldEspecie.getText().trim();
    String edadString = jTextFieldEdad.getText().trim();
    String pesoString = jTextFieldPeso.getText().trim();
    String tipo = (String) jComboBoxAlimentacion.getSelectedItem();
    String porcentajeFijo = jTextFieldPorcentajeFijo.getText().trim();
    String kgFijos = jTextFieldKgFijos.getText().trim();
    String sectorString = (String) jComboBoxSector.getSelectedItem();
    String paisSeleccionado = (String) jComboBoxPais.getSelectedItem();

    // Validación de campos obligatorios
    if (especieNombre.isEmpty() || edadString.isEmpty() || pesoString.isEmpty()
        || tipo.equals("Seleccione:") || sectorString.equals("Seleccione:")
        || paisSeleccionado == null || paisSeleccionado.toString().equals("Seleccione:")) {
        JOptionPane.showMessageDialog(null, "Complete todos los campos obligatorios.");
        return;
    }

    // Validación según el tipo
    if (tipo.equals("CARNIVORO") && porcentajeFijo.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Ingrese el porcentaje fijo para el carnívoro.");
        return;
    }

    if (tipo.equals("HERBIVORO") && kgFijos.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Ingrese los kilogramos fijos para el herbívoro.");
        return;
    }

    try {
        int edad = Integer.parseInt(edadString);
        double peso = Double.parseDouble(pesoString);
        Mamifero nuevo = null;

        // Buscar o crear especie
        Especie especie = Controlador.getEspeciePorNombre(especieNombre);
        if (especie == null) {
            especie = new Especie(especieNombre, TipoAlimentacion.valueOf(tipo),
                tipo.equals("CARNIVORO") ? Double.parseDouble(porcentajeFijo) : 0);
            Controlador.getEspecies().add(especie);
        }

        // Buscar sector
        Sector sector = Controlador.getSectorPorDescripcion(sectorString);
        if (sector == null) {
            JOptionPane.showMessageDialog(null, "Sector no encontrado.");
            return;
        }

        // Crear animal según tipo y pasar el país
        if (tipo.equals("CARNIVORO")) {
            nuevo = new Carnivoro(edad, peso, especie, sector, paisSeleccionado);
        } else {
            double kg = Double.parseDouble(kgFijos);
            nuevo = new Herbivoro(edad, peso, especie, sector, paisSeleccionado, kg);
        }

        Controlador.agregarAnimal(nuevo);
        JOptionPane.showMessageDialog(null, "Animal agregado correctamente.");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error al agregar animal: " + e.getMessage());
    }
    
     // Limpiar los campos de texto y reiniciar los ComboBox
        jTextFieldEspecie.setText("");
        jTextFieldEdad.setText("");
        jTextFieldPeso.setText("");
        jTextFieldPorcentajeFijo.setText("");
        jTextFieldKgFijos.setText(""); 
        jComboBoxAlimentacion.setSelectedIndex(0);
        jComboBoxSector.setSelectedIndex(0);
        jComboBoxPais.setSelectedIndex(0);    
        
    }//GEN-LAST:event_jButtonAgregarAnimalActionPerformed

