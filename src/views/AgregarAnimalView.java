    private void actualizarComboSectores(String tipoAlimentacion) {
        jComboBoxSector.removeAllItems();
        jComboBoxSector.addItem("Seleccione:");
        for (Sector sector : sectoresDisponibles) {
            if (sector.getTipoAlimentacion().toString().equalsIgnoreCase(tipoAlimentacion)) {
                jComboBoxSector.addItem(sector.toString());
            }
        }
    }
    
